def auth(spf: str, dkim: str, dmarc: str, domain: str, mailfrom: str) -> str:
    dkim_part = f"dkim={dkim} header.i=@{domain} header.s=s1 header.b=TESTSIG" if dkim == "pass" else f"dkim={dkim}"
    return (
        f"mx.google.com; {dkim_part}; spf={spf} (google.com: domain of {mailfrom} result {spf}) "
        f"smtp.mailfrom={mailfrom}; dmarc={dmarc} (p=REJECT sp=REJECT dis=NONE) header.from={domain}"
    )


def message(
    n: int,
    subject: str,
    sender: str,
    domain: str,
    *,
    spf: str = "pass",
    dkim: str = "pass",
    dmarc: str = "pass",
    ip: str = "198.51.100.25",
    return_path: str | None = None,
    reply_to: str | None = None,
) -> EmailMessage:
    when = format_datetime(START + timedelta(minutes=7 * n))
    return_path = return_path or f"bounce@{domain}"
    msg = EmailMessage()
    msg["Delivered-To"] = "you@example.com"
    msg["Received"] = f"by 2002:a05:6a10:{n:x}::1 with SMTP id sample{n}; {when}"
    msg["Received"] = (
        f"from mx.sender.example (mx.sender.example. [{ip}]) by mx.google.com with ESMTPS id sample{n}; {when}"
    )
    msg["Authentication-Results"] = auth(spf, dkim, dmarc, domain, return_path)
    msg["Return-Path"] = f"<{return_path}>"
    msg["From"] = sender
    if reply_to:
        msg["Reply-To"] = reply_to
    msg["To"] = "you@example.com"
    msg["Subject"] = f"[TEST SAMPLE] {subject}"
    msg["Date"] = when
    msg["Message-ID"] = f"<sample-{n}@phishcheck.test>"
    return msg


def body(msg: EmailMessage, text: str, html: str | None = None) -> EmailMessage:
    msg.set_content(f"{NOTE}\n\n{text}\n")
    if html is not None:
        msg.add_alternative(f"<html><body><p>{NOTE}</p>{html}</body></html>", subtype="html")
    return msg


def zip_bytes(files: dict[str, bytes]) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in files.items():
            archive.writestr(zipfile.ZipInfo(name, date_time=(2026, 11, 18, 9, 0, 0)), data)
    return buffer.getvalue()


IDN_HOST = "northwіndbank.example".encode("idna").decode()  # Cyrillic 'і' in place of 'i'

SAMPLES: list[tuple[str, str, list[str], EmailMessage]] = []


def sample(path: str, verdict: str, findings: list[str], msg: EmailMessage) -> None:
    SAMPLES.append((path, verdict, findings, msg))


