"""Generate the labelled test emails in ``samples/``.

These are inert fixtures for the test suite, not real or sendable phishing:

* every subject starts with ``[TEST SAMPLE]`` and every body says it is a test,
* the impersonated brand is fictional ("Northwind Bank", northwindbank.example),
* every domain uses the reserved ``.example`` TLD (RFC 2606) and every IP is
  from the documentation ranges 198.51.100.0/24 and 203.0.113.0/24 (RFC 5737),
* "executables" are a two-byte ``MZ`` header plus text: they cannot run.

Each phishing sample isolates one family of techniques; the clean samples
contain look-alike-but-legitimate patterns that must not be flagged.
``samples/expected.json`` records what each file must trigger.

Run:  python scripts/generate_samples.py
"""

